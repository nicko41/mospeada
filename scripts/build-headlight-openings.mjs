// Carry the two already-approved source face deletions into the runtime copy.
// Preserve the source GLB and every position/normal/color attribute verbatim.
import fs from 'node:fs'
import assert from 'node:assert/strict'
import { Matrix4, Vector3 } from 'three'
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js'
import { frontGeometryKey } from '../src/vehicle/frontTransformMath.js'

const data=JSON.parse(fs.readFileSync('public/transformations/cyclone-front-battloid.json'))
const before=JSON.parse(fs.readFileSync('.local/armor-geometry-sync/motorcycle-before.json'))
const current=JSON.parse(fs.readFileSync(data.motionHierarchySources[0].path))
const report=JSON.parse(fs.readFileSync('artifacts/armor-geometry-sync/report.json'))
const bytes=fs.readFileSync('public/models/mospeada/cyclone-vr052f.glb')
globalThis.self=globalThis;globalThis.createImageBitmap=async()=>({width:1,height:1,close(){}})
const gltf=await new GLTFLoader().parseAsync(bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength),'')
const meshes=new Map();gltf.scene.traverse(n=>{if(n.isMesh)meshes.set(frontGeometryKey(n),n)})
const baked=new Matrix4().fromArray(data.importMatrix).multiply(new Matrix4().fromArray(data.originalAssemblyMatrix))
const patches=[]
for(const change of report.changes){
  const source=before.pieces.find(p=>p.id===change.pieceId),now=current.pieces.find(p=>p.id===change.pieceId)
  const record=data.records.find(r=>r.pieceIds.includes(change.pieceId)),mesh=meshes.get(record.key)
  assert.ok(mesh&&!mesh.geometry.index,'Expected original non-indexed housing')
  const positions=mesh.geometry.attributes.position,remove=[]
  for(const faceId of change.removedFaceIds){
    assert.ok(!now.faces.some(f=>f.id===faceId),'Face must already be deleted in the authored Motorcycle JSON')
    const face=source.faces.find(f=>f.id===faceId)
    const points=face.vertices.map(id=>new Vector3(...source.vertices.find(v=>v.id===id).point).applyMatrix4(baked))
    for(let i=0;i<positions.count;i+=3){
      if([i,i+1,i+2].every(j=>points.some(p=>p.distanceTo(new Vector3().fromBufferAttribute(positions,j))<1e-6)))remove.push(i)
    }
    assert.equal(remove.length,face.vertices.length-2,'Remove only the triangles belonging to the persistent face ID')
  }
  patches.push({key:record.key,pieceId:change.pieceId,faceIds:change.removedFaceIds,vertexCount:positions.count,removeTriangleStarts:remove})
}
fs.writeFileSync('src/vehicle/headlightOpeningsData.js',`// Generated by scripts/build-headlight-openings.mjs; source faces identified by persistent IDs.\nexport default ${JSON.stringify(patches,null,2)}\n`)
