import assert from 'node:assert/strict'
import fs from 'node:fs'
import {connect} from './browser-cdp.mjs'

const c=await connect(),report={},wait=ms=>new Promise(resolve=>setTimeout(resolve,ms))
async function until(expression,message,timeout=15000){const end=Date.now()+timeout;while(Date.now()<end){if(await c.evaluate(expression))return;await wait(100)}throw Error(message)}
const key=(code,down)=>c.send('Input.dispatchKeyEvent',{type:down?'keyDown':'keyUp',code,key:code==='ShiftLeft'?'Shift':code==='Space'?' ':code.slice(3).toLowerCase()})
async function tap(code){await key(code,true);await key(code,false)}
const count=name=>c.evaluate(`__AUDIO_QA__.calls.filter(call=>call.name===${JSON.stringify(name)}).length`)
try{
  await until("!!window.__MOSPEADA__?.runtime.gallant&&!document.querySelector('#entry-preloader')",'Gameplay not ready',180000)
  await c.evaluate(`(()=>{window.__FOREST_OPENING__?.finish();__MOSPEADA__.reset();const a=__SFX__;window.__AUDIO_QA__={original:a.play,calls:[]};a.play=function(name,options){const voice=__AUDIO_QA__.original.call(this,name,options);if(voice)__AUDIO_QA__.calls.push({name,loop:voice.loop,rate:voice.playbackRate.value,detune:voice.detune.value});return voice};return true})()`)
  await tap('KeyV')
  await until("!!window.__CYCLONE_ENGINE_AUDIO__?.loop",'No continuous engine at idle')
  await c.evaluate('window.__AUDIO_QA__.engine=__CYCLONE_ENGINE_AUDIO__.loop;true')
  await key('KeyW',true)
  await until('__CYCLONE_ENGINE_AUDIO__.model.output.normalizedRpm>.05','Dynamic engine did not respond to throttle')
  await c.evaluate('__MOSPEADA__.runtime.state.speed=29;true')
  await until('__CYCLONE_ENGINE_AUDIO__.model.output.normalizedRpm>.3','Dynamic engine did not follow physical speed')
  assert.ok(await c.evaluate('__AUDIO_QA__.engine===__CYCLONE_ENGINE_AUDIO__.loop'))
  await key('ShiftLeft',true)
  await until("__AUDIO_QA__.calls.some(call=>call.name==='cycloneBoost')",'No effective Cyclone boost')
  const boosts=await count('cycloneBoost');await wait(1800);assert.equal(await count('cycloneBoost'),boosts,'Holding Shift must not replay the boost')
  await key('ShiftLeft',false);await key('KeyW',false)
  report.cyclone=await c.evaluate('({boosts:__MOSPEADA__.runtime.state.boostCount,calls:__AUDIO_QA__.calls.slice()})')
  await c.evaluate(`(()=>{const d=__MOSPEADA__;d.reset();const e=d.runtime.transformEntry;e.phase='complete';e.poseBlend=1;__FRONT_BATTLOID__.store.seek(1);return true})()`)
  await until('__MOSPEADA__.runtime.armorController.active','Armor did not activate')
  await key('KeyW',true);await key('ShiftLeft',true)
  await until("__AUDIO_QA__.calls.some(call=>call.name==='armorStrafe')",'No actual Armor strafe')
  const first=await count('armorStrafe');await wait(1100);assert.equal(await count('armorStrafe'),first)
  await key('KeyW',false);await key('KeyA',true)
  await until(`__AUDIO_QA__.calls.filter(call=>call.name==='armorStrafe').length>${first}`,'Direction change did not play a new strafe')
  const changed=await count('armorStrafe');await wait(700);assert.equal(await count('armorStrafe'),changed)
  await key('KeyA',false);await key('ShiftLeft',false)
  await tap('KeyG')
  await until("__MOSPEADA__.runtime.armorController.state.mode==='ARMOR_GROUND'&&!__MOSPEADA__.runtime.armorController.state.groundLanding",'Ground landing did not finish')
  await key('KeyW',true)
  await until("__AUDIO_QA__.calls.filter(call=>call.name==='armorStep').length>=4",'Native gait footsteps missing',20000)
  await key('ShiftLeft',true)
  await until("__MOSPEADA__.runtime.scottInstance.clip==='Armor_Run'&&__MOSPEADA__.runtime.armorController.state.speed>10.5",'Armor run did not reach its unchanged physical speed')
  report.armorRun=await c.evaluate(`(()=>{const r=__MOSPEADA__.runtime,i=r.scottInstance,speed=r.armorController.state.speed;return{speed,rate:i.action.getEffectiveTimeScale(),nativeRate:Math.min(3,speed/i.armorLocomotion.info.get('Armor_Run').speed)}})()`)
  assert.ok(Math.abs(report.armorRun.rate/report.armorRun.nativeRate-.8)<1e-6);assert.ok(report.armorRun.rate>1&&report.armorRun.rate<1.8)
  await key('ShiftLeft',false)
  await key('KeyW',false)
  const landings=await count('armorLanding')
  await key('Space',true);await wait(400);await key('Space',false)
  await until('__MOSPEADA__.runtime.armorController.state.height>.5','Jump never left the ground')
  await until(`__AUDIO_QA__.calls.filter(call=>call.name==='armorLanding').length>${landings}`,'Jump landing sound missing',20000)
  report.armor=await c.evaluate(`({strafe:__AUDIO_QA__.calls.filter(call=>call.name==='armorStrafe'),steps:__AUDIO_QA__.calls.filter(call=>call.name==='armorStep').length,landings:__AUDIO_QA__.calls.filter(call=>call.name==='armorLanding').length})`)
  assert.ok(report.armor.strafe.every(call=>!call.loop))
  assert.ok(await c.evaluate('__AUDIO_QA__.calls.filter(call=>call.name!=="cycloneEngineLoop").every(call=>call.rate===1&&call.detune===0)'))
  report.errors=c.events.filter(event=>event.method==='Runtime.exceptionThrown').map(event=>event.params.exceptionDetails.exception?.description||event.params.exceptionDetails.text)
  assert.deepEqual(report.errors,[])
  fs.mkdirSync('artifacts/gameplay-sfx',{recursive:true});fs.writeFileSync('artifacts/gameplay-sfx/movement-validation.json',JSON.stringify(report,null,2)+'\n')
  console.log(JSON.stringify(report,null,2))
}finally{
  for(const code of ['KeyW','KeyA','ShiftLeft','Space'])await key(code,false).catch(()=>{})
  await c.evaluate('if(window.__AUDIO_QA__){__SFX__.play=__AUDIO_QA__.original;delete window.__AUDIO_QA__};__MOSPEADA__.reset();true').catch(()=>{})
  c.close()
}
