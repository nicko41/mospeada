import {crashSiteSample} from './forestCrashSite.js'

export const FOREST_PATH_MASK=Object.freeze({inner:1.2,outer:4.5})
export const forestPathX=z=>Math.sin(z*.013)*20+Math.sin(z*.033)*3
export const forestBranchZ=x=>-62+Math.sin(x*.018)*16
// The old branching layout remains a height/seed ledger only. Plano 1 has one
// forward route (-Z), ending behind the playable clearing before the thicket.
export const FOREST_ROUTE_REAR=10
export function forestRouteDistance(x,z){
  const along=Math.min(z,FOREST_ROUTE_REAR)
  return Math.hypot(x-forestPathX(along),Math.max(0,z-FOREST_ROUTE_REAR))
}
const smooth=(a,b,v)=>{const t=Math.max(0,Math.min(1,(v-a)/(b-a)));return t*t*(3-2*t)}
export function forestEarthWeight(x,z){
  const distance=forestRouteDistance(x,z)
  return Math.max(1-smooth(FOREST_PATH_MASK.inner,FOREST_PATH_MASK.outer,distance),crashSiteSample(x,z).earth)
}
// Same path definition as the contact sampler; the crash mask texture is also
// generated by crashSiteSample. No screen reads or colour-based classification.
export const forestPathMaskGLSL=`
float forestPathEarth(vec2 ground){
  float along=min(ground.y,${FOREST_ROUTE_REAR.toFixed(1)});
  float pathX=sin(along*.013)*20.0+sin(along*.033)*3.0;
  float distanceToRoute=length(vec2(ground.x-pathX,max(0.0,ground.y-${FOREST_ROUTE_REAR.toFixed(1)})));
  return 1.0-smoothstep(${FOREST_PATH_MASK.inner.toFixed(1)},${FOREST_PATH_MASK.outer.toFixed(1)},distanceToRoute);
}`
